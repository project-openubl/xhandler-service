/**
 * Registers of sales and purchases as files (DESIGN.md §11.9): CSV and Excel for people, PLE for
 * old periods, SIRE's layout. Generated by a job: {@code 202} with the job, then the report.
 */
@Path("/api/v1/tenants/{tenantId}/companies/{companyId}/reports")
public class ReportResource {

    private final CompanyManager companyManager;

    public record ReportRequest(
            @NotBlank @Pattern(regexp = "sales|purchases") String register,
            @NotBlank @Pattern(regexp = "csv|xlsx|ple|sire") String format,
            @NotBlank @Pattern(regexp = "\\d{4}(0[1-9]|1[0-2])") String period) {}

    public record ReportView(
            UUID id, String register, String format, String period, String sunatEnv, String status, String fileName, Integer rows,
            String detail, UUID jobId, Instant createdAt, Instant doneAt) {}

    private final TenantAccess access;
    private final Jobs jobs;
    private final ReportProvider reportProvider;
    private final FileStore files;
    private final AuditManager auditor;

    public ReportResource(TenantAccess access, Jobs jobs, ReportProvider reportProvider, FileStore files, AuditManager auditor, CompanyManager companyManager) {
        this.companyManager = companyManager;
        this.access = access;
        this.jobs = jobs;
        this.reportProvider = reportProvider;
        this.files = files;
        this.auditor = auditor;
    }

    @APIResponse(responseCode = "202", description = "Reporte solicitado; lo genera un trabajo (job_id).",
            content = @Content(mediaType = "application/json", schema = @Schema(implementation = ReportView.class)))
    @Operation(operationId = "createReport")
    @POST
    @Transactional
    public Response create(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId, @Valid ReportRequest request) {
        TenantScope scope = access.enter(tenantId, Role.OPERATOR);
        CompanyModel company = companyManager.getCompany(companyId);
        UUID id = Ids.newId();
        reportProvider.addReport(id, tenantId, company.getId(), company.getSunatEnv(), request.register(), request.format(), request.period(),
                scope.actor().auditName());
        JobModel job = jobs.enqueue(scope, ReportJob.NAME, 4, Map.of("report_id", id.toString()), List.of(), null);
        reportProvider.setReportJob(id, job.getId());
        auditor.record(scope, "report.requested", "company", companyId,
                Map.of("register", request.register(), "format", request.format(), "period", request.period()));
        return Response.status(202).entity(view(id)).build();
    }

    @Operation(operationId = "listReports", summary = "Reportes de la empresa, los más recientes primero")
    @GET
    @Transactional
    public Page<ReportView> list(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId,
            @QueryParam("limit") Integer limit, @QueryParam("offset") Integer offset) {
        access.enter(tenantId, Role.VIEWER);
        companyManager.getCompany(companyId);
        int size = Page.limit(limit);
        int start = Page.offset(offset);
        List<UUID> ids = reportProvider.getReportIds(companyId, size, start);
        return new Page<>(ids.stream().map(this::view).toList(), size, start);
    }

    @Operation(operationId = "getReport")
    @GET
    @Path("/{reportId}")
    @Transactional
    public ReportView get(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId,
            @PathParam("reportId") UUID reportId) {
        access.enter(tenantId, Role.VIEWER);
        companyManager.getCompany(companyId);
        ReportView view = view(reportId);
        if (view == null || !companyId.equals(companyOf(reportId))) {
            throw ApiException.notFound();
        }
        return view;
    }

    @APIResponse(responseCode = "200", description = "El reporte: CSV, Excel, ZIP (SIRE) o texto (PLE).", content = {
            @Content(mediaType = "text/csv", schema = @Schema(type = SchemaType.STRING, format = "binary")),
            @Content(mediaType = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", schema = @Schema(type = SchemaType.STRING, format = "binary")),
            @Content(mediaType = "application/zip", schema = @Schema(type = SchemaType.STRING, format = "binary")),
            @Content(mediaType = "text/plain", schema = @Schema(type = SchemaType.STRING, format = "binary"))
    })
    @Operation(operationId = "downloadReportFile")
    @GET
    @Path("/{reportId}/file")
    @Transactional
    public Response file(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId,
            @PathParam("reportId") UUID reportId) {
        TenantScope scope = access.enter(tenantId, Role.VIEWER);
        companyManager.getCompany(companyId);
        java.util.Optional<ReportProvider.ReportFile> found = reportProvider.getReportFile(reportId, companyId);
        if (found.isEmpty() || found.get().fileRef() == null) {
            throw ApiException.notFound();
        }
        auditor.record(scope, "report.downloaded", "company", companyId, Map.of("report_id", reportId.toString()));
        ReportProvider.ReportFile reportFile = found.get();
        String name = reportFile.fileName();
        String type = switch (reportFile.format()) {
            case "csv" -> "text/csv; charset=utf-8";
            case "xlsx" -> "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
            case "sire" -> "application/zip";
            default -> "text/plain; charset=utf-8";
        };
        return Response.ok(files.get(reportFile.fileRef())).type(type)
                .header("Content-Disposition", "attachment; filename=\"" + name + "\"").header("X-Content-Type-Options", "nosniff").build();
    }

    private UUID companyOf(UUID reportId) {
        return reportProvider.getReportCompanyId(reportId).orElse(null);
    }

    private ReportView view(UUID id) {
        return reportProvider.getReport(id).map(r -> new ReportView(r.id(), r.register(), r.format(), r.period(), r.sunatEnv(), r.status(),
                r.fileName(), r.rows(), r.detail(), r.jobId(), r.createdAt(), r.doneAt())).orElse(null);
    }
}
